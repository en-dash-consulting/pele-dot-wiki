// Draws the first Pele diagram of the home race, theme lab and phone demo in a real browser (same fonts
// and text measurement readers get), and saves the SVG so the HTML ships with the finished drawing.
// Run `npm run prerender` after changing a demo, its styles, the examples or the pele version.
import { spawn, execSync } from 'node:child_process'
import { writeFileSync, existsSync, rmSync } from 'node:fs'
import { chromium } from '@playwright/test'
import { ROOT, SNAPSHOT, TARGETS, prerenderKey } from './prerender-key.mjs'

if (existsSync(SNAPSHOT)) rmSync(SNAPSHOT)
execSync('npm run build', { cwd: ROOT, stdio: 'inherit' })
const port = 4199
const server = spawn('npx', ['vite', 'preview', '--port', String(port), '--strictPort'], { cwd: ROOT, stdio: 'ignore' })
try {
  for (let i = 0; i < 50; i++) { try { await fetch(`http://localhost:${port}/`); break } catch { await new Promise(r => setTimeout(r, 200)) } }
  const browser = await chromium.launch()
  const page = await browser.newPage({ viewport: { width: 1280, height: 900 } })
  await page.route(/googletagmanager\.com|google-analytics\.com/, r => r.fulfill({ status: 204, body: '' }))
  const items = []
  for (const path of [...new Set(TARGETS.map(t => t.path))]) {
    await page.goto(`http://localhost:${port}${path}`, { waitUntil: 'load' })
    await page.evaluate(() => document.fonts.ready)
    const targets = TARGETS.filter(t => t.path === path)
    await page.locator(targets[0].sel).scrollIntoViewIfNeeded()
    await page.locator(targets[0].sel).dispatchEvent('pointerdown')
    for (const t of targets) await page.locator(`${t.sel} svg`).first().waitFor()
    await page.waitForTimeout(800)
    for (const t of targets) items.push({ page: t.page, attr: t.attr, html: await page.locator(t.sel).innerHTML() })
  }
  await browser.close()
  writeFileSync(SNAPSHOT, JSON.stringify({ key: prerenderKey(), note: 'Generated by scripts/prerender.mjs. Do not edit.', items }, null, 1) + '\n')
  console.log(`prerender: saved ${items.length} drawings (${Math.round(JSON.stringify(items).length / 1024)} KB)`)
} finally { server.kill() }
execSync('npm run build', { cwd: ROOT, stdio: 'inherit' })
